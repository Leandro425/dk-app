-- 5. RLS
-- Enabling RLS without a select policy would hide every article, so make sure one exists.
do $$
begin
    if not exists (
        select 1
        from pg_policies
        where schemaname = 'public'
          and tablename = 'article'
          and cmd in ('SELECT', 'ALL')
    ) then
        create policy "Authenticated select on article"
        on public.article
        for select
        to authenticated
        using (true);
    end if;
end;
$$;

alter table public.article enable row level security;

drop policy if exists "Admin insert on article" on public.article;
create policy "Admin insert on article"
on public.article
for insert
to authenticated
with check (public.is_admin());

drop policy if exists "Admin update on article" on public.article;
create policy "Admin update on article"
on public.article
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "Admin delete on article" on public.article;
create policy "Admin delete on article"
on public.article
for delete
to authenticated
using (public.is_admin());

-- 6. Foreign keys to article must block the delete (article_private, created below, keeps its cascade)
do $$
declare
    fk record;
begin
    for fk in
        select c.conrelid::regclass as tbl, c.conname, pg_get_constraintdef(c.oid) as def
        from pg_constraint c
        where c.contype = 'f'
          and c.confrelid = 'public.article'::regclass
          and c.conrelid <> coalesce(to_regclass('public.article_private'), 0::regclass)
          and c.confdeltype in ('c', 'n', 'd') -- cascade, set null, set default
    loop
        execute format('alter table %s drop constraint %I', fk.tbl, fk.conname);
        execute format(
            'alter table %s add constraint %I %s',
            fk.tbl,
            fk.conname,
            regexp_replace(fk.def, 'ON DELETE (CASCADE|SET NULL|SET DEFAULT)( \([^)]*\))?', 'ON DELETE RESTRICT')
        );
        raise notice 'Foreign key %.% now uses on delete restrict', fk.tbl, fk.conname;
    end loop;
end;
$$;

-- 7. Private article data
create table if not exists public.article_private (
    article_id bigint primary key references public.article(id) on delete cascade,
    sales_price numeric(10, 2) check (sales_price >= 0),
    updated_at timestamptz not null default now()
);

comment on table public.article_private is 'Admin-only article data (commercially sensitive). One row per article.';
comment on column public.article_private.sales_price is 'Net sales price in EUR per article unit.';

alter table public.article_private enable row level security;

drop policy if exists "Admin all on article_private" on public.article_private;
create policy "Admin all on article_private"
on public.article_private
for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

-- 8. Atomic save
create or replace function public.save_article(p_id bigint, p_article jsonb, p_private jsonb)
returns bigint
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
    v_id bigint := p_id;
    a public.article;
    p public.article_private;
begin
    if not public.is_admin() then
        raise exception 'Article data is restricted to administrators'
            using errcode = '42501';
    end if;

    a := jsonb_populate_record(null::public.article, p_article);
    p := jsonb_populate_record(null::public.article_private, p_private);

    if v_id is null then
        insert into public.article (external_id, name, unit, piecework_wage, piecework_packaging, notes, active)
        values (
            a.external_id, a.name, coalesce(a.unit, 'piece'), a.piecework_wage, a.piecework_packaging,
            a.notes, coalesce(a.active, true)
        )
        returning id into v_id;
    else
        update public.article
        set external_id = a.external_id,
            name = a.name,
            unit = coalesce(a.unit, 'piece'),
            piecework_wage = a.piecework_wage,
            piecework_packaging = a.piecework_packaging,
            notes = a.notes,
            active = coalesce(a.active, true)
        where id = v_id;

        if not found then
            raise exception 'Article % not found', v_id
                using errcode = 'P0002';
        end if;
    end if;

    insert into public.article_private (article_id, sales_price, updated_at)
    values (v_id, p.sales_price, now())
    on conflict (article_id) do update
    set sales_price = excluded.sales_price,
        updated_at = now();

    return v_id;
end;
$$;

comment on function public.save_article(bigint, jsonb, jsonb) is
    'Admin only. Creates (p_id null) or fully replaces an article and its article_private row in one transaction. Returns the article id.';

revoke all on function public.save_article(bigint, jsonb, jsonb) from public;
grant execute on function public.save_article(bigint, jsonb, jsonb) to authenticated;
