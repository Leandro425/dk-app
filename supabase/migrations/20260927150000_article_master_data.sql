-- Articles module in the controlling area
-- Run this in the Supabase SQL editor (or via `supabase db push`) BEFORE deploying the frontend.
-- The old frontend keeps working: it only reads article rows.
--
-- Context: public.article was created in the dashboard (id, external_id, name,
-- piecework_wage, piecework_packaging, ...) and is not under version control.
-- Nobody could create or change articles through the app.
--
--   1. column types: external_id becomes text if it is not; piecework_wage / piecework_packaging must be numeric
--   2. guard: refuses to run while existing data would break the new constraints
--   3. id: make sure inserts get an id (identity), if the dashboard did not set one up
--   4. master data columns: unit, notes, active; constraints on number, name, unit and wages
--   5. RLS: read stays open to all authenticated users; insert/update/delete admin only
--   6. foreign keys referencing article block the delete, so an article with reports or
--      deliveries cannot be deleted, only archived
--   7. article_private (1:1 with article): sales price, admin only
--   8. save_article(p_id, p_article, p_private)  admin-only atomic create/update of both rows

-- 1. Column types
do $$
declare
    col record;
begin
    for col in
        select a.attname, format_type(a.atttypid, a.atttypmod) as type_name, t.typcategory
        from pg_attribute a
        join pg_type t on t.oid = a.atttypid
        where a.attrelid = 'public.article'::regclass
          and a.attname in ('external_id', 'piecework_wage', 'piecework_packaging')
          and a.attnum > 0
          and not a.attisdropped
    loop
        if col.attname = 'external_id' and col.typcategory <> 'S' then
            execute 'alter table public.article alter column external_id type text using external_id::text';
            raise notice 'article.external_id changed from % to text', col.type_name;
        elsif col.attname <> 'external_id' and col.typcategory <> 'N' then
            raise exception 'article.% has type %, expected a number. Adjust this migration before running it.',
                col.attname, col.type_name;
        end if;
    end loop;
end;
$$;

alter table public.article
    add column if not exists external_id text,
    add column if not exists piecework_wage numeric,
    add column if not exists piecework_packaging numeric;

-- 2. Guard
do $$
declare
    problems text;
begin
    select string_agg(problem, E'\n') into problems
    from (
        select format('article %s: article number (external_id) is empty', id) as problem
        from public.article
        where nullif(trim(external_id), '') is null
        union all
        select format('article number %L is used by articles %s', trim(external_id), string_agg(id::text, ', '))
        from public.article
        where nullif(trim(external_id), '') is not null
        group by trim(external_id)
        having count(*) > 1
        union all
        select format('article %s: name is empty', id)
        from public.article
        where nullif(trim(name), '') is null
        union all
        select format('article %s: piecework_wage %s is negative', id, piecework_wage)
        from public.article
        where piecework_wage < 0
        union all
        select format('article %s: piecework_packaging %s is negative', id, piecework_packaging)
        from public.article
        where piecework_packaging < 0
    ) p;

    if problems is not null then
        raise exception E'Fix these article rows before running this migration:\n%', problems;
    end if;
end;
$$;

update public.article set external_id = trim(external_id) where external_id <> trim(external_id);
update public.article set name = trim(name) where name <> trim(name);

-- 3. id identity
do $$
begin
    if exists (
        select 1
        from pg_attribute a
        where a.attrelid = 'public.article'::regclass
          and a.attname = 'id'
          and a.attidentity = ''
          and not a.atthasdef
    ) then
        alter table public.article alter column id add generated by default as identity;
        perform setval(
            pg_get_serial_sequence('public.article', 'id'),
            coalesce((select max(id) from public.article), 0) + 1,
            false
        );
    end if;
end;
$$;

-- 4. Master data
alter table public.article
