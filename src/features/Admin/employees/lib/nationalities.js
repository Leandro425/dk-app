const NAMES = new Map(NATIONALITIES)

export const getNationalityName = (code) =>
    code === null || code === undefined ? '' : (NAMES.get(code) ?? String(code))

/** Select options "152 – Polen": codes listed in `preferredCodes` first (in that order), then alphabetically. */
export const getNationalityOptions = (preferredCodes = []) => {
    const rank = new Map(preferredCodes.map((code, index) => [code, index]))
    const rankOf = (code) => rank.get(code) ?? preferredCodes.length
    return [...NATIONALITIES]
        .sort(([a, nameA], [b, nameB]) => rankOf(a) - rankOf(b) || nameA.localeCompare(nameB, 'de'))
        .map(([code, name]) => ({ value: code, label: `${String(code).padStart(3, '0')} – ${name}` }))
}
